"""Vitals tile firmware for the Adafruit Feather RP2040 USB Host.

Receives 128x64 1-bit frames from the host over the USB CDC *data* channel and
pushes them to an SSD1306 OLED on the STEMMA QT / I2C bus. All layout and text
is rendered on the PC, so the Pico stays simple and the display looks exactly
like the PNG previews.

Protocol (host -> tile):
    b"\\xa5\\x5a" + 1024 bytes   one frame, SSD1306 page format
    b"VIT?\\n"                  handshake
Tile -> host:
    b"VIT1\\n"                  handshake reply

Wiring: OLED VCC -> 3V, GND -> GND, SDA -> SDA, SCL -> SCL (STEMMA QT works).
"""

import sys
import time

import board
import busio
import microcontroller
import usb_cdc

WIDTH = 128
HEIGHT = 64
FRAME_BYTES = WIDTH * HEIGHT // 8  # 1024
MAGIC = b"\xa5\x5a"
IDLE_AFTER = 4.0  # seconds without a frame before showing the splash again

# Identity: the chip UID is also the USB serial number, so the host can tell
# this exact board from any other RP2040 running the same firmware.
UID = microcontroller.cpu.uid.hex().upper()
BOARD_ID = board.board_id
IDENTITY = ("VIT1 %s %s\n" % (UID, BOARD_ID)).encode()

# 128x64 splash frame ("WAITING FOR HOST"), generated by host/make_splash.py.
try:
    with open("/splash.bin", "rb") as fp:
        SPLASH = fp.read()
except OSError:
    SPLASH = bytes(FRAME_BYTES)

# SSD1306 128x64 initialisation (charge pump on, horizontal addressing).
INIT = bytes(
    (
        0xAE,  # display off
        0xD5, 0x80,  # clock divide
        0xA8, 0x3F,  # multiplex 64
        0xD3, 0x00,  # display offset
        0x40,  # start line 0
        0x8D, 0x14,  # charge pump on
        0x20, 0x00,  # horizontal addressing
        0xA1,  # segment remap
        0xC8,  # COM scan reversed
        0xDA, 0x12,  # COM pins
        0x81, 0xCF,  # contrast
        0xD9, 0xF1,  # pre-charge
        0xDB, 0x40,  # VCOMH
        0xA4,  # resume from RAM
        0xA6,  # normal (not inverted)
        0x2E,  # no scrolling
        0xAF,  # display on
    )
)

i2c = busio.I2C(board.SCL, board.SDA, frequency=400_000)
try:
    import digitalio

    led = digitalio.DigitalInOut(board.LED)
    led.direction = digitalio.Direction.OUTPUT
except Exception:
    led = None
ADDR = None
frame_count = 0


def find_display():
    """Scan the bus for the SSD1306 (0x3C, sometimes 0x3D)."""
    while not i2c.try_lock():
        pass
    try:
        found = i2c.scan()
    finally:
        i2c.unlock()
    print("I2C scan:", ["0x%02x" % a for a in found])
    for candidate in (0x3C, 0x3D):
        if candidate in found:
            return candidate
    return None


def write(buf):
    """busio.I2C requires the bus to be locked around every transfer."""
    while not i2c.try_lock():
        pass
    try:
        i2c.writeto(ADDR, buf)
    finally:
        i2c.unlock()


def show(frame):
    """Push a 1024-byte page-format frame to the display."""
    while not i2c.try_lock():
        pass
    try:
        for page in range(8):
            start = page * WIDTH
            i2c.writeto(ADDR, b"\x40" + frame[start:start + WIDTH])
    finally:
        i2c.unlock()


def safe_show(frame):
    """Draw a frame, ignoring a display that is unplugged or glitching."""
    try:
        show(frame)
    except OSError as exc:
        print("I2C error:", exc)


def sleep_blink():
    while True:
        if led:
            led.value = not led.value
        time.sleep(0.15)


def run():
    global ADDR, frame_count

    ADDR = find_display()
    print("SSD1306:", "0x%02x" % ADDR if ADDR else "NOT FOUND")
    if ADDR is None:
        print("Check the OLED wiring (3V, GND, SDA, SCL).")
        sleep_blink()

    write(b"\x00" + INIT)
    safe_show(SPLASH)

    data = usb_cdc.data
    if data is None:
        print("USB data channel disabled - is boot.py present?")
        sleep_blink()
    data.timeout = 0.05
    print("Waiting for host frames...")

    buf = bytearray()
    last_frame = time.monotonic()
    splash_visible = True

    while True:
        chunk = data.read(64)
        if chunk:
            buf.extend(chunk)

        # ASCII commands are interleaved with the binary frame stream.
        if buf and 0x20 <= buf[0] < 0x7F:
            newline = buf.find(b"\n")
            if newline >= 0:
                line = bytes(buf[:newline])
                buf = bytearray(buf[newline + 1:])
                if line == b"VIT?":
                    data.write(IDENTITY)
                    print("Host connected")
                elif line == b"ID?":
                    data.write(IDENTITY)
                elif line == b"STAT?":
                    data.write(b"FRAMES %d\n" % frame_count)

        # Frames: wait until a whole one is buffered, then blit.
        while True:
            start = buf.find(MAGIC)
            if start < 0:
                # keep a trailing 0xA5 in case the magic straddles two reads
                if buf.endswith(b"\xa5"):
                    buf = bytearray(buf[-1:])
                else:
                    buf = bytearray()
                break
            if start:
                buf = bytearray(buf[start:])
            if len(buf) < 2 + FRAME_BYTES:
                break
            frame = bytes(buf[2:2 + FRAME_BYTES])
            buf = bytearray(buf[2 + FRAME_BYTES:])
            safe_show(frame)
            last_frame = time.monotonic()
            splash_visible = False
            frame_count += 1
            if led:
                led.value = False
            if frame_count % 20 == 0:
                print("frames:", frame_count)

        if not splash_visible and time.monotonic() - last_frame > IDLE_AFTER:
            safe_show(SPLASH)
            splash_visible = True
            print("Host silent - showing splash")
            if led:
                led.value = True


try:
    run()
except Exception as exc:  # log to CIRCUITPY so failures survive a tiny console
    try:
        with open("/error.txt", "w") as fp:
            sys.print_exception(exc, fp)
    except Exception:
        pass
    print("FATAL:", exc)
    raise
